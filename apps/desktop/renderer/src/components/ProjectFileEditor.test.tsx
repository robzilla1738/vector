// @vitest-environment jsdom
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { bridge } from '../bridge';
import { ProjectFileEditor } from './ProjectFileEditor';
let host: HTMLDivElement, root: ReturnType<typeof createRoot>;
const props={projectId:'project-a',taskId:'task-a',taskRevision:7,attached:true,disabled:false};
const file=(projectId:string,name:string,content:string,sha256='a'.repeat(64))=>({projectId,name,content,sha256});
beforeEach(()=>{vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT',true);vi.stubGlobal('requestAnimationFrame',(callback:FrameRequestCallback)=>setTimeout(()=>callback(0),0));const storage=new Map<string,string>();vi.stubGlobal('localStorage',{getItem:(key:string)=>storage.get(key)??null,setItem:(key:string,value:string)=>storage.set(key,value),removeItem:(key:string)=>storage.delete(key)});host=document.createElement('div');document.body.append(host);root=createRoot(host);});
afterEach(async()=>{await act(async()=>root.unmount());host.remove();vi.restoreAllMocks();vi.unstubAllGlobals();});
it('restores file drafts and saves against the recorded disk revision',async()=>{
 vi.spyOn(bridge,'listProjectFiles').mockResolvedValue(['a.ts','b.ts']);
 vi.spyOn(bridge,'readProjectFile').mockImplementation(async(project,name)=>file(project,name,`disk ${name}`));
 const save=vi.spyOn(bridge,'saveProjectFile').mockImplementation(async(project,name,_sha,content)=>({...file(project,name,content,'b'.repeat(64)),recoveryPath:'/recovery/copy'}));
 localStorage.setItem('aux.file-draft.v1:project-a:a.ts',JSON.stringify({content:'preserved draft',sha256:'a'.repeat(64)}));
 await act(async()=>root.render(<ProjectFileEditor {...props}/>));
 const pick=async(name:string)=>act(async()=>host.querySelector<HTMLButtonElement>(`[role="treeitem"][title="${name}"]`)!.click());
 await pick('a.ts');expect(host.querySelector<HTMLTextAreaElement>('textarea')?.value).toBe('preserved draft');
 await pick('b.ts');await pick('a.ts');expect(host.querySelector<HTMLTextAreaElement>('textarea')?.value).toBe('preserved draft');
 await act(async()=>[...host.querySelectorAll<HTMLButtonElement>('button')].find(button=>button.textContent==='Save file')!.click());
 expect(save).toHaveBeenCalledWith('project-a','a.ts','a'.repeat(64),'preserved draft');
 expect(localStorage.getItem('aux.file-draft.v1:project-a:a.ts')).toBeNull();
 expect(host.querySelector('.ui-detail-pane header')?.textContent).toContain('Saved to this checkout');
});
it('keeps a late read from another project out of the selected-file pane',async()=>{
 vi.spyOn(bridge,'listProjectFiles').mockResolvedValue(['a.ts']);
 let finish:(value:ReturnType<typeof file>)=>void=()=>{};
 vi.spyOn(bridge,'readProjectFile').mockReturnValue(new Promise(resolve=>{finish=resolve;}));
 await act(async()=>root.render(<ProjectFileEditor {...props}/>));
 await act(async()=>host.querySelector<HTMLButtonElement>('[role="treeitem"]')!.click());
 await act(async()=>root.render(<ProjectFileEditor {...props} projectId="project-b"/>));
 await act(async()=>finish(file('project-a','a.ts','old private contents')));
 expect(host.textContent).not.toContain('old private contents');expect(host.querySelector('textarea')).toBeNull();
});
it('keeps external file conflicts explicit and destructive menu actions disabled for a draft',async()=>{
 vi.spyOn(bridge,'listProjectFiles').mockResolvedValue(['a.ts']);
 vi.spyOn(bridge,'readProjectFile').mockResolvedValue(file('project-a','a.ts','external edit','b'.repeat(64)));
 localStorage.setItem('aux.file-draft.v1:project-a:a.ts',JSON.stringify({content:'my draft',sha256:'a'.repeat(64)}));
 await act(async()=>root.render(<ProjectFileEditor {...props}/>));
 await act(async()=>host.querySelector<HTMLButtonElement>('[role="treeitem"]')!.click());
 expect(host.querySelector<HTMLTextAreaElement>('textarea')?.value).toBe('my draft');
 expect([...host.querySelectorAll<HTMLButtonElement>('button')].find(button=>button.textContent==='Save file')!.disabled).toBe(true);
 expect(host.querySelector('[aria-label="External file contents"]')?.textContent).toBe('external edit');
 await act(async()=>host.querySelector<HTMLButtonElement>('[aria-label="Actions for a.ts"]')!.click());
 expect([...document.querySelectorAll<HTMLButtonElement>('[role="menuitem"]')].find(button=>button.textContent==='Delete')!.disabled).toBe(true);
 await act(async()=>document.querySelector('[role="menu"]')!.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true})));
 await act(async()=>[...host.querySelectorAll<HTMLButtonElement>('button')].find(button=>button.textContent==='Use external version')!.click());
 expect(host.querySelector<HTMLTextAreaElement>('textarea')?.value).toBe('external edit');
 expect(localStorage.getItem('aux.file-draft.v1:project-a:a.ts')).toBeNull();
});
