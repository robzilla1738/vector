import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {createServer} from 'node:http';
import {loadSuppliedCli} from '../../scripts/e2e/supplied-cli.mjs';
const root=process.cwd();
const proposal=JSON.parse(await fs.readFile('docs/integration/proposed/development-dp-signing/proposal.json'));
const home=await fs.realpath(proposal.exactExistingDisposableHome);
assert.equal(createHash('sha256').update(home).digest('hex'),proposal.exactScope);
assert(home.includes('/T/aux-provided-dp-approval-'));
const candidate=path.resolve(process.argv[2]);
const resource=path.join(candidate,'Aux.app/Contents/Resources/aux');
const directory=await fs.mkdtemp(path.join(home,'unpaid-browser-smoke-'));
process.env.HOME=home;process.env.CFFIXED_USER_HOME=home;process.env.AUX_HOME=home;
process.env.DAEMON_BASE_URL='http://127.0.0.1:21520';process.env.AUX_CLI_UPDATE_CHECK='0';
const helpers=await loadSuppliedCli('out/provided-source-audit/cli-original.mjs',directory,new URL('../../vendor/provided/cli-adapter.mjs',import.meta.url).href);
const auth=helpers.daemonAuthorizer({clientKind:'cli',daemonUrl:process.env.DAEMON_BASE_URL,signChallenge:async({signingInput})=>{
 const result=spawnSync(path.join(resource,'native/Aux Native Carrier.app/Contents/MacOS/aux-native-carrier'),[path.join(resource,'apps/daemon/Aux Daemon.app/Contents/Resources/native/provided-native.node'),'cdp-sign'],{input:JSON.stringify({challenge:Buffer.from(signingInput).toString('base64')}),encoding:'utf8',env:{...process.env,DYLD_INSERT_LIBRARIES:path.join(resource,'native/libaux-native-boundary.dylib'),AUX_ENABLE_PROVIDED_NATIVE_CARRIER:'1',AUX_NATIVE_KEYCHAIN_SCOPE:proposal.exactScope},timeout:15000});
 assert.equal(result.status,0,'Scoped challenge signer failed');
 const signed=JSON.parse(result.stdout);assert(signed.signature&&!signed.error,'Scoped challenge rejected');return Buffer.from(signed.signature,'base64');
}});
// Capture only the token generated by the supplied authorizer in memory. No log/file.
let token;
const originalFetch=globalThis.fetch;
globalThis.fetch=async(input,init)=>{const response=await originalFetch(input,init);if(String(input).endsWith('/auth/daemon/session')&&response.ok)token=(await response.clone().json()).access_token;return response;};
try { const health=await auth.fetchDaemon('http://127.0.0.1:21520/health');assert(health.ok); }
finally { globalThis.fetch=originalFetch; }
assert(token);process.env.DAEMON_AUTH_JWT=token;
const daemon=helpers.createDaemonClient();delete process.env.DAEMON_AUTH_JWT;token=undefined;
const rpc=daemon.trpcClient;
// The supplied CLI runRepl owner uses these exact RPCs, without an AI session.
const expectedProfileId = '70f3b1d5-acdc-4528-b6ea-78aa6e7168b9';
const accountId = 1;
const accounts = await rpc.accounts.summary.query();
const account = accounts.accounts.find(a => a.id === accountId);
assert(account, 'Expected disposable account1 missing');
const binding = account.profileBindings?.find(b => b.profileId === expectedProfileId);
assert(binding?.profilePath?.startsWith(home + path.sep), 'Exact disposable profile binding required');
const resolved = await helpers.resolveAccount(rpc, 'u1');
assert.equal(resolved.accountId, accountId);
const identity = {accountId, accountCreatedAt: resolved.account.createdAt};
const marker = 'AUX_UNPAID_BROWSER_' + createHash('sha256').update(directory).digest('hex').slice(0, 16);
let visited = false;
const fixture = createServer((req, res) => {
  if (req.url !== '/aux-browser-check') { res.writeHead(404); res.end(); return; }
  visited = true;
  res.writeHead(200, {'content-type':'text/html; charset=utf-8', 'cache-control':'no-store'});
  res.end('<!doctype html><title>Aux unpaid browser check</title><h1>Local browser check</h1><p>' + marker + '</p>');
});
await new Promise((resolve, reject) => { fixture.once('error', reject); fixture.listen(0, '127.0.0.1', resolve); });
const fixtureUrl = `http://127.0.0.1:${fixture.address().port}/aux-browser-check`;
const report = {accountId, profileId: expectedProfileId, daemonAuth: true, paidRequest: false, browserControl: false};
let session;
try {
  session = await rpc.cli.replStart.mutate({...identity, profileId: expectedProfileId});
  assert(session.id, 'Real supplied REPL session required');
  const code = `let auxSmokeTab; try { auxSmokeTab = await openTab(${JSON.stringify(fixtureUrl)}); const auxSmokeSnapshot = await snapshot(auxSmokeTab); if (!auxSmokeSnapshot.tree.includes(${JSON.stringify(marker)})) throw new Error('Dummy snapshot marker missing'); console.log(auxSmokeSnapshot.tree); } finally { if (auxSmokeTab) { await closeTab(auxSmokeTab); console.log('AUX_UNPAID_OWN_TAB_CLOSED'); } }`;
  const result = await rpc.cli.replRun.mutate({...identity, id: session.id, code});
  assert(!result.error, 'Actual supplied REPL returned an error; inspect only the disposable REPL diagnostics');
  const output = result.content.filter(p => p.type === 'text').map(p => p.text ?? '').join('\n');
  assert(visited && output.includes(marker), 'Real local navigation and snapshot required');
  assert(output.includes('AUX_UNPAID_OWN_TAB_CLOSED'), 'Dummy tab must close through supplied API');
  report.browserControl = true;
  report.snapshot = true;
  report.ownTabClosed = true;
} finally {
  fixture.closeAllConnections();
  await new Promise(resolve => fixture.close(resolve));
  if (session) {
    await rpc.cli.replClose.mutate({...identity, id: session.id});
    report.replClosed = true;
  }
  await fs.writeFile(path.join(directory, 'report.json'), JSON.stringify(report, null, 2) + '\n', {mode:0o600});
}
console.log(JSON.stringify(report));
process.exit(0);
