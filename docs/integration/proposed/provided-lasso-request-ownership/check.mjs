import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {edits:[edit]}=JSON.parse(await readFile(new URL('patch.json',import.meta.url)));
const pending=[],messages=[];
const nw=(request,options)=>new Promise((resolve,reject)=>pending.push({request,options,resolve,reject}));
const port={name:'lasso:transform',onMessage:{addListener(fn){this.fn=fn}},onDisconnect:{addListener(fn){this.fn=fn}},postMessage(m){messages.push(m)}};
const rw=new Function('tw','nw',edit.replace+';return rw;')('lasso:transform',nw);
await rw(port);
const start=request=>port.onMessage.fn({type:'lasso:transform:start',request});
start('A');start('B');
assert(pending[0].options.signal.aborted);
pending[0].options.onChunk('late A');pending[0].reject(new Error('late A failure'));
await new Promise(resolve=>setImmediate(resolve));
assert.equal(messages.length,0);
port.onMessage.fn({type:'lasso:transform:abort'});
assert(pending[1].options.signal.aborted,'late A must not orphan B abort owner');
pending[1].resolve();await new Promise(resolve=>setImmediate(resolve));assert.equal(messages.length,0);
start('C');pending[2].options.onChunk('C');pending[2].resolve();
await new Promise(resolve=>setImmediate(resolve));
assert.deepEqual(messages,[{type:'lasso:transform:chunk',chunk:'C'},{type:'lasso:transform:complete'}]);
start('D');port.onDisconnect.fn();assert(pending[3].options.signal.aborted);
pending[3].options.onChunk('late D');pending[3].resolve();await new Promise(resolve=>setImmediate(resolve));assert.equal(messages.length,2);
console.log('Actual transformed port race, abort, disconnect and completion passed');
