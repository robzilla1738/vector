// Inactive native producer SOURCE. No module initializer or admission override.
import Foundation

enum AuxCleanRuntimeHostError:Error {case pairing,hostChanged}
struct AuxCleanRuntimeHostContext {
    let runtime:AuxRuntimeCapturedCommandContext
    let before:AuxObservedCleanHost
    let after:AuxObservedCleanHost
    let state2LaunchAuthorized=false
    let writerCustodyVerified=false
    let authorityProvenanceVerified=false
    private init(runtime:AuxRuntimeCapturedCommandContext,before:AuxObservedCleanHost,after:AuxObservedCleanHost){self.runtime=runtime;self.before=before;self.after=after}
    // This helper only validates public content. Passing it cannot construct a
    // host observation, call Security or manufacture a command context.
    static func validatePairing(policy:AuxCleanHostPolicy,selection:AuxRuntimeSelection)throws {
        try policy.validate()
        guard [.daemon,.cli].contains(policy.role),policy.scope==selection.scope,policy.accessGroup==selection.accessGroup else{throw AuxCleanRuntimeHostError.pairing}
        // Selectors are generated by the actual minimal runtime selection, never
        // accepted from JS, an arbitrary caller core or a captured-success flag.
        let service="aux."+policy.scope+".installation.v2"
        let accounts=["metadata":"meta","signing":"sig","kem":"kem","wrappedRoot":"dk"]
        for role in AuxRuntimeSelection.roles {
            let target=try selection.selector(role)
            guard target.service==service,target.account==service+"."+accounts[role]!,target.accessGroup==policy.accessGroup else{throw AuxCleanRuntimeHostError.pairing}
        }
    }
    // SOURCE ONLY: calling this performs real current-host inspection, FOUR
    // exact protected reads and existing authority imports. Never run by tests.
    // A trusted native producer must authenticate the immutable policy/selected
    // manifest and independently enforce complete writer/cohort admission first.
    static func capture(policy:AuxCleanHostPolicy,selection:AuxRuntimeSelection)throws->Self {
        try validatePairing(policy:policy,selection:selection)
        let before=try AuxCleanHostPreflight.inspect(policy:policy)
        let rows=try AuxRuntimeDataProtectionCapture.capture(selection)
        // Reinspect after protected reads BEFORE importing private authority.
        let afterCapture=try AuxCleanHostPreflight.inspect(policy:policy)
        guard before.policySha256==afterCapture.policySha256,before.scope==afterCapture.scope,before.accessGroup==afterCapture.accessGroup,before.role==afterCapture.role else{throw AuxCleanRuntimeHostError.hostChanged}
        let runtime=try AuxRuntimeCapturedCommandContext.validate(selection:selection,rows:rows)
        let after=try AuxCleanHostPreflight.inspect(policy:policy)
        guard before.policySha256==after.policySha256,before.role==after.role,before.scope==after.scope,before.accessGroup==after.accessGroup,
              before.scope==selection.scope,before.accessGroup==selection.accessGroup else{throw AuxCleanRuntimeHostError.hostChanged}
        return .init(runtime:runtime,before:before,after:after)
    }
}
