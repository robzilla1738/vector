#!/usr/bin/env python3
"""Create isolated Node archive successors; never mutate a pinned input.

Run through scripts/native-build.py. The plan pins each original archive and
replacement object. Member order/count and every ordinary member's bytes are
verified; archive symbol indexes are regenerated by the platform archiver.
"""
import argparse
import collections
import hashlib
import json
import pathlib
import shutil
import subprocess
import tempfile

def sha(path):
    with open(path, 'rb') as file:
        return hashlib.file_digest(file, 'sha256').hexdigest()

def members(path):
    # Stream the actual BSD archive once; do not extract hundreds of members.
    result = []
    with open(path, 'rb') as file:
        if file.read(8) != b'!<arch>\n':
            raise ValueError('Not a regular BSD archive')
        while header := file.read(60):
            if len(header) != 60 or header[58:] != b'`\n':
                raise ValueError('Invalid archive header')
            name = header[:16].decode('ascii').strip()
            size = int(header[48:58]); remaining = size
            if name.startswith('#1/'):
                length = int(name[3:])
                if length > remaining: raise ValueError('Invalid extended name')
                name = file.read(length).rstrip(b'\0').decode('utf-8')
                remaining -= length
            else:
                name = name.rstrip('/')
            digest = hashlib.sha256()
            while remaining:
                chunk = file.read(min(remaining, 1024 * 1024))
                if not chunk: raise ValueError('Truncated archive')
                digest.update(chunk); remaining -= len(chunk)
            if size % 2 and len(file.read(1)) != 1: raise ValueError('Missing alignment')
            if not name.startswith('__.SYMDEF'):
                result.append((name, digest.hexdigest()))
    return result

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('plan'); parser.add_argument('output')
    args = parser.parse_args()
    plan_path = pathlib.Path(args.plan).resolve()
    plan = json.loads(plan_path.read_text())
    out = pathlib.Path(args.output).resolve()
    out.mkdir(mode=0o700, parents=False, exist_ok=False)
    receipt = {'format': 'aux.isolated-node-archives.v1', 'passed': False,
               'planSha256': sha(plan_path), 'archives': [], 'linked': False,
               'executed': False, 'signed': False, 'originalsChanged': False}
    try:
        for entry in plan['archives']:
            original = pathlib.Path(entry['path']).resolve()
            if sha(original) != entry['sha256']: raise ValueError('Archive pin mismatch')
            before = members(original)
            counts = collections.Counter(name for name, _ in before)
            expected = dict(before)
            if len(expected) != len(before): raise ValueError('Duplicate member names')
            destination = out / original.name
            shutil.copyfile(original, destination)
            with tempfile.TemporaryDirectory(dir=out, prefix='members-') as temp:
                copied = []
                for replacement in entry['replacements']:
                    name = replacement['member']
                    if pathlib.Path(name).name != name or counts[name] != 1:
                        raise ValueError('Replacement member not unique')
                    source = pathlib.Path(replacement['path']).resolve()
                    if sha(source) != replacement['sha256']: raise ValueError('Object pin mismatch')
                    target = pathlib.Path(temp) / name
                    shutil.copyfile(source, target)
                    copied.append(str(target)); expected[name] = replacement['sha256']
                subprocess.run(['/usr/bin/ar', '-r', str(destination), *copied], check=True,
                               capture_output=True)
            after = members(destination)
            if [n for n, _ in after] != [n for n, _ in before] or dict(after) != expected:
                raise ValueError('Archive member bytes/order mismatch')
            if sha(original) != entry['sha256']: raise ValueError('Original archive changed')
            receipt['archives'].append({'path': str(destination), 'sha256': sha(destination),
                'memberCount': len(after), 'replaced': [r['member'] for r in entry['replacements']],
                'allOtherMemberBytesPreserved': True})
        receipt['passed'] = True
    finally:
        (out / 'receipt.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(json.dumps({'passed': True, 'receipt': str(out / 'receipt.json')}))

if __name__ == '__main__': main()
