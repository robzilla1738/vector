// Deterministic source transformation. Refreshing subscriptions is a separate reviewed input change.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { parseArgs } from "node:util";
const { values } = parseArgs({ options: {
  "list-directory": { type: "string" },
  "contracts-output": { type: "string" },
  "native-output": { type: "string" },
} });
if (!values["list-directory"] || !values["contracts-output"] || !values["native-output"]) {
  throw new Error("Required: --list-directory PATH --contracts-output PATH --native-output PATH");
}
const directory = resolve(values["list-directory"]);
const manifest = JSON.parse(await readFile(join(directory, "manifest.json"), "utf8"));
const sources = [];
let total = 0;
for (const source of manifest.sources) {
  const id = createHash("sha256").update(source.url).digest("hex").slice(0, 12);
  if (source.file !== `${id}.txt`) throw new Error(`Invalid bundled filename: ${source.name}`);
  const bytes = await readFile(join(directory, source.file));
  total += bytes.byteLength;
  const hash = createHash("sha256").update(bytes).digest("hex");
  if (hash !== source.sha256 || id !== source.id || bytes.byteLength !== source.bytes ||
    source.file !== `${id}.txt` || bytes.byteLength > 16 * 1024 * 1024) throw new Error(`Bundled list changed: ${source.name}`);
  new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  const { file, upstream, ...header } = source;
  sources.push(header);
}
if (sources.length > 20 || total > 64 * 1024 * 1024) throw new Error("Bundled filter snapshot exceeds its limits");
await writeFile(resolve(values["contracts-output"]),
  `// Generated by chromium/filter-lists/build-defaults.mjs.\n// Full rule texts remain native assets; runtime startup loads only exact headers.\nexport const BUNDLED_FILTER_SOURCES = ${JSON.stringify(sources, null, 2)} as const;\n`);
await writeFile(resolve(values["native-output"]), `// Copyright 2026 The Aux Authors. BSD-3-Clause.
// Generated by chromium/filter-lists/build-defaults.mjs from exact pinned source assets.
#ifndef CHROME_COMMON_AUX_FILTER_DEFAULTS_H_
#define CHROME_COMMON_AUX_FILTER_DEFAULTS_H_
namespace aux {
inline constexpr char kBundledFilterManifest[] = R"AUXFILTERS(${JSON.stringify(manifest.sources)})AUXFILTERS";
}  // namespace aux
#endif  // CHROME_COMMON_AUX_FILTER_DEFAULTS_H_
`);
