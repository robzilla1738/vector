import { shell, settings, press } from '../fixtures/legacy-ui.mjs';
import { createNativeSpace, saveNativeTask } from '../fixtures/legacy-task.mjs';

export const journey = { id: 'automations-schedule', title: 'Create paused reviewed schedule and site-event Skills, persist and fire one scheduled occurrence', features: ['automations'], devAcceptance: ['automations', 'spaces'], needs: ['accessibility', 'screen-recording'], model: 'none', launch: {}, timeoutMs: 420000, owner: 'LJ' };
export async function run(t) {
  let space;
  let task;
  let scheduled;
  let event;
  const routines = () => t.rpc('routines.list', { workspaceId: space.workspaceId });
  const choose = async (label, value) => {
    await press(t, shell(label, 'AXPopUpButton'));
    await press(t, { name: value, role: 'AXMenuItem', match: 'exact', scope: 'window', index: 0 });
  };
  await t.step('create saved task and capped paused schedule through Settings', { kind: 'ui', features: ['automations'] }, async () => {
    space = await createNativeSpace(t, 'Automation fixture Space');
    task = await saveNativeTask(t, space, 'Automation fixture source', 'Inspect only the disposable automation fixture.', 'Inspect the fixture before any action.');
    await settings(t, 'Automations');
    await choose('Automation Space', space.name);
    await press(t, shell('Create automation', 'AXButton'));
    await choose('Automation source task', task.title);
    await t.ax.type('Fixture scheduled Skill', shell('New automation name', 'AXTextField'));
    await t.ax.type('4.50', shell('New automation model spend cap', 'AXTextField'));
    await press(t, shell('Every day', 'AXButton'));
    await press(t, shell('Create paused Skill', 'AXButton'));
    scheduled = await t.until('paused reviewed schedule persisted', async () => (await routines()).find(item => item.title === 'Fixture scheduled Skill'));
    t.assert.equal(scheduled.sourceTaskId, task.taskId);
    t.assert.equal(scheduled.sourceTaskRevision, task.revision);
    t.assert.equal(scheduled.paused, true);
    t.assert.equal(scheduled.reviewRequired, true);
    t.assert.equal(scheduled.spendCapUsd, 4.5);
    t.assert.deepEqual(scheduled.successCriteria, task.criteria);
    t.assert.deepEqual(scheduled.trigger.days, [0, 1, 2, 3, 4, 5, 6]);
    t.assert.equal(scheduled.trigger.kind, 'schedule');
    const ax = await t.ax.dump({ scope: 'shell' });
    await t.capture('automation-schedule-paused');
    return { ax, rpc: scheduled };
  });
  await t.step('create exact-origin site-event Skill without granting execution', { kind: 'ui', features: ['automations'] }, async () => {
    await press(t, shell('Create automation', 'AXButton'));
    await choose('Automation source task', task.title);
    await t.ax.type('Fixture site-event Skill', shell('New automation name', 'AXTextField'));
    await choose('Trigger', 'Site notification');
    await t.ax.type('https://example.com', shell('Exact site origin', 'AXTextField'));
    await press(t, shell('Create paused Skill', 'AXButton'));
    event = await t.until('paused exact site-event persisted', async () => (await routines()).find(item => item.title === 'Fixture site-event Skill'));
    t.assert.deepEqual(event.trigger, { kind: 'site_notification', origin: 'https://example.com' });
    t.assert.equal(event.paused, true);
    t.assert.equal(event.sourceTaskId, task.taskId);
    t.assert.ok(event.siteOrigins.includes('https://example.com'));
    const ax = await t.ax.dump({ scope: 'shell' });
    await t.capture('automation-site-event-paused');
    return { ax, rpc: event };
  });
  await t.restart();
  await t.step('persist Skills and fire a near-future reviewed schedule exactly once', { kind: 'ui', features: ['automations'] }, async () => {
    const persisted = await routines();
    t.assert.ok(persisted.some(item => item.routineId === scheduled.routineId && item.paused && item.spendCapUsd === 4.5));
    t.assert.ok(persisted.some(item => item.routineId === event.routineId && item.paused && item.trigger.kind === 'site_notification'));
    await settings(t, 'Automations');
    await choose('Automation Space', space.name);
    await press(t, shell('Create automation', 'AXButton'));
    await choose('Automation source task', task.title);
    await t.ax.type('Fixture live scheduled Skill', shell('New automation name', 'AXTextField'));
    const target = new Date(Math.ceil((Date.now() + 3 * 60000) / 60000) * 60000);
    const parts = Intl.DateTimeFormat('en-US', { timeZone: scheduled.trigger.timezone, hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).formatToParts(target);
    const hour = Number(parts.find(part => part.type === 'hour').value);
    const minute = Number(parts.find(part => part.type === 'minute').value);
    await t.ax.type(`${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}`, shell('Time'));
    await press(t, shell('Every day', 'AXButton'));
    await press(t, shell('Create paused Skill', 'AXButton'));
    const live = await t.until('new near-future schedule saved', async () => (await routines()).find(item => item.title === 'Fixture live scheduled Skill'));
    t.assert.equal(live.trigger.timezone, scheduled.trigger.timezone);
    t.assert.equal(live.trigger.hour, hour);
    t.assert.equal(live.trigger.minute, minute);
    t.assert.deepEqual(live.trigger.days, [0, 1, 2, 3, 4, 5, 6]);
    // Newly created Skills are prepended in the Settings list.
    await t.ax.waitFor(shell(live.title, 'AXStaticText'));
    t.assert.equal((await routines())[0].routineId, live.routineId);
    await press(t, shell('Resume', 'AXButton'));
    await t.until('only live fixture schedule resumed', async () => (await routines()).some(item => item.routineId === live.routineId && !item.paused));
    t.assert.ok((await routines()).filter(item => item.routineId !== live.routineId).every(item => item.paused));
    const item = await t.until('live scheduled occurrence awaits human review without dispatch', async () => (await t.rpc('routines.inbox', { workspaceId: space.workspaceId })).find(row => row.run.routineId === live.routineId && row.run.status === 'needs_review'), 300000);
    t.assert.ok(item.run.occurrenceIdentity?.length > 0);
    const runs = await t.rpc('routines.runs', { routineId: live.routineId });
    t.assert.equal(runs.filter(run => run.occurrenceIdentity === item.run.occurrenceIdentity).length, 1);
    t.assert.equal(item.run.runId, undefined, 'A reviewed schedule occurrence must not dispatch a model run');
    const ax = await t.ax.dump({ scope: 'shell' });
    await t.capture('automation-scheduled-review');
    return { ax, rpc: { persisted, live, occurrence: item, runs } };
  });
}
