import {launchAux,root} from './launch.mjs';
import {mkdtempSync,mkdirSync,writeFileSync} from 'node:fs';
import {createServer} from 'node:http';
import assert from 'node:assert/strict';
mkdirSync(root+'/release/test-artifacts/tabs',{recursive:true});
const dir=mkdtempSync('/tmp/aux-toolbar-');
const server=createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.end(`<title>Glass fixture</title><style>body{margin:0;background:${req.url==='/dark'?'#080827':'white'};color:${req.url==='/dark'?'white':'black'};font:24px sans-serif;min-height:300vh}header{height:60px;display:flex;gap:30px}button{margin:120px 40px;padding:20px}</style><header>High contrast page · Navigation · Resources</header><button onclick="this.textContent='Page clicked'">Page action</button><script>window.framesSeen=0;function tick(){window.framesSeen++;requestAnimationFrame(tick)}tick();</script>`);});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}`;
const {app,page}=await launchAux({args:['--use-mock-keychain'],env:{...process.env,AUX_PROFILE_DIR:dir+'/profile',AUX_DATA_DIR:dir+'/data',AUX_LOAD_DOTENV:'0'}});
page.setDefaultTimeout(15000);
try {
 await page.locator('.aux-home').waitFor();
 await app.evaluate(({BaseWindow})=>BaseWindow.getAllWindows()[0].setBounds({x:100,y:100,width:1200,height:800}));
 await page.evaluate(()=>window.aux.invoke('settings.set',{tabLayout:'vertical',theme:'dark'}));
 await page.locator('.tabs-vertical').waitFor();
 if(await page.getByRole('button',{name:'Collapse sidebar',exact:true}).isVisible()) await page.getByRole('button',{name:'Collapse sidebar',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.sidebar').getAttribute('aria-hidden')==='true');
 for(const variant of ['white','dark']) {
  await page.evaluate(url=>window.aux.invoke('pages.open',{url,activate:true}),base+'/'+variant);
  await page.waitForFunction(()=>document.querySelector('.main-col.has-page'));
  await page.waitForFunction(async url=>(await window.aux.invoke('pages.list',{})).some(p=>p.url===url&&!p.loading),base+'/'+variant);
  const bar=page.locator('.main-col > .toolbar');
  await bar.dispatchEvent('pointerenter');
  await page.waitForFunction(()=>document.querySelector('.toolbar-revealed'));
  await bar.evaluate(el=>Promise.all(el.getAnimations().map(a=>a.finished)));
  assert.equal(await bar.evaluate(el=>getComputedStyle(el).webkitAppRegion),'drag');
  assert.equal(await bar.locator('.tb-right').evaluate(el=>getComputedStyle(el).webkitAppRegion),'drag');
  assert.equal(await bar.locator('.icon-btn').first().evaluate(el=>getComputedStyle(el).webkitAppRegion),'no-drag');
  assert.equal(await page.locator('.stage-card.has-page').evaluate(el=>getComputedStyle(el).webkitAppRegion),'no-drag');
  const input=bar.locator('input');
  await bar.locator('.cb-display').click();
  assert.equal(await input.evaluate(el=>el===document.activeElement),true);
  await bar.dispatchEvent('pointerleave');
  await page.mouse.move(600,400);
  await new Promise(r=>setTimeout(r,750));
  assert.equal(await page.locator('.toolbar-revealed').count(),1,'focused address stays visible after pointer leaves');
  const focusedScroll=await app.evaluate(async({webContents},url)=>webContents.getAllWebContents().find(w=>w.getURL()===url).executeJavaScript('scrollY'),base+'/'+variant);
  await page.mouse.wheel(0,250);
  await new Promise(r=>setTimeout(r,200));
  const afterFocusedScroll=await app.evaluate(async({webContents},url)=>webContents.getAllWebContents().find(w=>w.getURL()===url).executeJavaScript('scrollY'),base+'/'+variant);
  assert.ok(afterFocusedScroll>focusedScroll,'wheel scroll while URL owns focus, without a page click first');
  await page.waitForFunction(()=>!document.querySelector('.toolbar-stacked'),'scroll releases the native page');
  await page.mouse.wheel(0,250);
  await new Promise(r=>setTimeout(r,200));
  const afterHiddenScroll=await app.evaluate(async({webContents},url)=>webContents.getAllWebContents().find(w=>w.getURL()===url).executeJavaScript('scrollY'),base+'/'+variant);
  assert.ok(afterHiddenScroll>afterFocusedScroll,'continued wheel input reaches the page after the toolbar is lowered');
  await bar.dispatchEvent('pointerenter');
  await page.waitForFunction(()=>document.querySelector('.toolbar-revealed'));
  await bar.evaluate(el=>Promise.all(el.getAnimations().map(a=>a.finished)));
  assert.equal(await page.evaluate(()=>document.documentElement.dataset.toolbarTone),variant==='white'?'light':'dark');
  assert.equal(await bar.locator('.cb-title').evaluate(el=>getComputedStyle(el).color),variant==='white'?'rgb(41, 41, 41)':'rgb(241, 241, 241)');
  const frost=await app.evaluate(async({webContents},url)=>{
   const wc=webContents.getAllWebContents().find(w=>w.getURL()===url);
   return wc.executeJavaScript(`(()=>{const el=document.getElementById('aux-toolbar-glass');return el&&{blur:getComputedStyle(el).backdropFilter,height:el.offsetHeight}})()`);
  },base+'/'+variant);
  assert.match(frost.blur,/blur\(20px\)/);assert.equal(frost.height,52);
  await app.evaluate(async({webContents},url)=>webContents.getAllWebContents().find(w=>w.getURL()===url).executeJavaScript('scrollTo(0,0)'),base+'/'+variant);
  const nativeRead=script=>app.evaluate(async({webContents},{url,script})=>webContents.getAllWebContents().find(w=>w.getURL()===url).executeJavaScript(script),{url:base+'/'+variant,script});
  const frames=await nativeRead('window.framesSeen');
  const buttonBox=await nativeRead('(()=>{const b=document.querySelector("button").getBoundingClientRect();return {x:b.x,y:b.y,width:b.width,height:b.height,scroll:scrollY}})()');
  await page.mouse.click(buttonBox.x+buttonBox.width/2,buttonBox.y+buttonBox.height/2);
  for(let retry=0;retry<20 && await nativeRead('document.querySelector("button").textContent')!=='Page clicked';retry++) await new Promise(r=>setTimeout(r,50));
  assert.equal(await nativeRead('document.querySelector("button").textContent'),'Page clicked','page click works with bar raised');
  await page.mouse.move(600,400);await page.mouse.wheel(0,250);
  await new Promise(r=>setTimeout(r,150));
  assert.ok(await nativeRead('scrollY')>0,'page scroll works with bar raised');
  assert.ok(await nativeRead('window.framesSeen')>frames,'page animation continues');
  const png=await app.evaluate(async({desktopCapturer,BaseWindow})=>{const id=BaseWindow.getAllWindows()[0].getMediaSourceId();const sources=await desktopCapturer.getSources({types:['window'],thumbnailSize:{width:2400,height:1600}});return sources.find(s=>s.id===id)?.thumbnail.toPNG().toString('base64');});
  if(png)writeFileSync(root+`/release/test-artifacts/tabs/toolbar-${variant}.png`,Buffer.from(png,'base64'));
  await page.mouse.move(600,400);
  await bar.dispatchEvent('pointerleave');
  await page.evaluate(()=>document.activeElement?.blur());
  await page.waitForFunction(()=>!document.querySelector('.toolbar-revealed'));
  const exiting=await app.evaluate(async({webContents},url)=>webContents.getAllWebContents().find(w=>w.getURL()===url).executeJavaScript(`(()=>{const el=document.getElementById('aux-toolbar-glass');return el?el.style.opacity:'removed'})()`),base+'/'+variant);
  assert.ok(exiting==='0'||exiting==='removed','page frost exits with the controls');
  await page.waitForFunction(()=>!document.querySelector('.toolbar-stacked'));
  await bar.dispatchEvent('pointerenter');
  await page.waitForFunction(()=>document.querySelector('.toolbar-revealed'));
  await bar.evaluate(el=>Promise.all(el.getAnimations().map(a=>a.finished)));
  await bar.getByRole('button',{name:'Show sidebar',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.sidebar').getAttribute('aria-hidden')==='false');
  await page.locator('.sidebar').evaluate(el=>Promise.all(el.getAnimations().map(a=>a.finished)));
  await app.evaluate(({BaseWindow})=>BaseWindow.getAllWindows()[0].focus());
  const beforeDrag=await app.evaluate(({BaseWindow})=>BaseWindow.getAllWindows()[0].getBounds());
  await page.mouse.move(150,20);await page.mouse.down();await page.mouse.move(210,70,{steps:8});await page.mouse.up();
  await new Promise(r=>setTimeout(r,100));
  const afterDrag=await app.evaluate(({BaseWindow})=>BaseWindow.getAllWindows()[0].getBounds());
  assert.ok(beforeDrag.x!==afterDrag.x||beforeDrag.y!==afterDrag.y,'sidebar blank header moves the native window');
  await page.getByRole('button',{name:'Collapse sidebar',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.sidebar').getAttribute('aria-hidden')==='true');
  await bar.dispatchEvent('pointerleave');
  await page.mouse.move(600,400);
  await page.evaluate(()=>document.activeElement?.blur());
  await page.waitForFunction(()=>!document.querySelector('.toolbar-stacked'));
 }
 console.log('PASS glass across white/dark pages, click-to-edit URL, focus retention, sidebar button, native sidebar dragging, full hide and native captures.');
} finally {await app.evaluate(({app})=>app.exit(0)).catch(()=>{});server.closeAllConnections();await new Promise(r=>server.close(r));}
