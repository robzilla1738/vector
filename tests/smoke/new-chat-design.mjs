import {closeAux} from "./launch.mjs";
import {launchAux,root} from './launch.mjs';
import {mkdtempSync} from 'node:fs';
import assert from 'node:assert/strict';
const dir=mkdtempSync('/tmp/aux-new-chat-');
const {app,page}=await launchAux({args:['--use-mock-keychain'],env:{...process.env,AUX_PROFILE_DIR:dir+'/profile',AUX_DATA_DIR:dir+'/data',AUX_LOAD_DOTENV:'0'}});
try {
 await page.locator('.aux-home').waitFor();
 await app.evaluate(({BaseWindow})=>BaseWindow.getAllWindows()[0].setBounds({x:100,y:100,width:1440,height:900}));
 await page.waitForFunction(()=>innerWidth===1440);
 await page.evaluate(()=>window.aux.invoke('settings.set',{tabLayout:'vertical'}));
 if(await page.getByRole('button',{name:'Show sidebar',exact:true}).isVisible())await page.getByRole('button',{name:'Show sidebar',exact:true}).click();
 await page.locator('.sidebar').getByRole('button',{name:'New chat',exact:true}).click();
 await page.locator('.conversation-new').waitFor();
 const rect=selector=>page.locator(selector).boundingBox();
 const scroll=await rect('.conversation-scroll'),mark=await rect('.conversation-empty .aux-mark');
 assert.ok(Math.abs(mark.y+mark.height/2-(scroll.y+scroll.height/2))<3,'mark centered vertically');
 const compose=await rect('.conversation-input');assert.ok(compose.width>680,'composer wider than old 680px');
 await page.getByRole('button',{name:'Add context',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Image',exact:true}).isVisible(),true);
 await page.getByRole('button',{name:'Add context',exact:true}).click();
 await page.getByRole('button',{name:'Browser context',exact:true}).click();
 await page.getByRole('dialog',{name:'Browser context',exact:true}).getByRole('button',{name:/New browser tab/}).click();
 await page.getByRole('textbox',{name:'Reply to conversation'}).fill('A draft to verify composer sizing');
 await page.screenshot({path:root+'/release/test-artifacts/tabs/new-chat-wide.png'});
 await app.evaluate(({BaseWindow})=>{const win=BaseWindow.getAllWindows()[0];win.setMinimumSize(600,500);win.setBounds({x:100,y:100,width:780,height:680});});
 await page.waitForFunction(()=>innerWidth===780);
 assert.equal(await page.locator('.conversation').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
 assert.equal(await page.getByRole('textbox',{name:'Reply to conversation'}).inputValue(),'A draft to verify composer sizing');
 await page.screenshot({path:root+'/release/test-artifacts/tabs/new-chat-narrow.png'});
 console.log('PASS centered mark, wider composer, attachment controls, context selection, narrow layout and draft preservation.');
} finally {await closeAux(app);}
