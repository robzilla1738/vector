import {poll} from "./poll.mjs";
import {sidebarAction} from "./sidebar-action.mjs";
// Task draft continuity and revision conflicts in an isolated desktop profile.
import {createRequire} from 'node:module';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import assert from 'node:assert/strict';
const root=resolve(import.meta.dirname,'../..');
const {_electron}=createRequire(join(root,'packages/chromium-driver/package.json'))('playwright-core');
const electron=createRequire(join(root,'apps/desktop/package.json'))('electron');
const dir=mkdtempSync(join(tmpdir(),'aux-task-drafts-'));let app;
try {
 app=await _electron.launch({executablePath:electron,args:[join(root,'apps/desktop'),'--use-mock-keychain'],env:{PATH:process.env.PATH,HOME:dir,TMPDIR:dir,AUX_PROFILE_DIR:join(dir,'profile'),AUX_DATA_DIR:join(dir,'data'),AUX_LOAD_DOTENV:'0'}});
 let page;for(let i=0;i<100;i++){page=app.windows().find(p=>p.url().includes('renderer/index.html'));if(page)break;await new Promise(r=>setTimeout(r,100));}assert.ok(page);
 await page.locator('.aux-home').waitFor();await app.evaluate(({BaseWindow})=>BaseWindow.getAllWindows()[0].setSize(1200,944));
 const workspace=await page.evaluate(()=>window.aux.invoke('workspaces.create',{name:'Research'}));
 await page.evaluate(()=>window.aux.invoke('workspaces.create',{name:'Personal tasks'}));
 const open=()=>sidebarAction(page,'Tasks');await open();
 const tasks=page.getByRole('region',{name:'Tasks',exact:true});
 const space=tasks.getByLabel('Space',{exact:true});
 await space.selectOption({label:'Research'});
 await tasks.getByRole('button',{name:'New task',exact:true}).click();
 await tasks.getByLabel('Title',{exact:true}).fill('Compare options');
 await tasks.getByLabel('Objective',{exact:true}).fill('Compare the evidence carefully');
 await tasks.getByLabel('What must be true when this is done?').fill('Sources are cited');
 await space.selectOption({label:'Personal tasks'});
 await tasks.getByRole('button',{name:'New task',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#task-title')?.value==='');
 await tasks.getByLabel('Title',{exact:true}).fill('Separate draft');
 await space.selectOption({label:'Research'});
 await tasks.getByRole('button',{name:'New task',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#task-title')?.value==='Compare options');
 await tasks.getByRole('button',{name:'Close tasks',exact:true}).click();await page.reload();await page.locator('.aux-home').waitFor();await open();
 await tasks.getByRole('button',{name:'New task',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#task-title')?.value==='Compare options');
 assert.equal(await space.inputValue(),`workspace:${workspace.workspaceId}`);
 assert.equal((await page.evaluate(id=>window.aux.invoke('tasks.list',{workspaceId:id}),workspace.workspaceId)).length,0);
 await page.getByRole('button',{name:'Save task',exact:true}).click();
 await page.getByRole('button',{name:'Discard draft and reload saved task',exact:true}).waitFor();
 const [task]=await page.evaluate(id=>window.aux.invoke('tasks.list',{workspaceId:id}),workspace.workspaceId);
 await page.getByLabel('Objective',{exact:true}).fill('My unfinished local revision');
 await page.getByRole('button',{name:'Close tasks',exact:true}).click();
 await page.evaluate(task=>window.aux.invoke('tasks.update',{taskId:task.taskId,expectedRevision:task.revision,objective:'A newer shared objective'}),task);
 await open();await page.getByText('This task changed since your draft began.',{exact:false}).waitFor();
 assert.equal(await page.getByLabel('Objective',{exact:true}).inputValue(),'My unfinished local revision');
 assert.equal(await page.getByRole('button',{name:'Save task',exact:true}).isDisabled(),true);
 await page.getByText('Current saved task · revision 2',{exact:true}).click();
 await page.getByText('A newer shared objective',{exact:true}).waitFor();
 await page.screenshot({path:join(root,'release/test-artifacts/aux-task-draft-conflict.png')});
 await page.getByRole('button',{name:'Use my draft with this revision',exact:true}).click();
 await page.getByRole('button',{name:'Save task',exact:true}).click();
 await poll(page, async id=>(await window.aux.invoke('tasks.get',{taskId:id})).task.revision===3,task.taskId);
 const final=await page.evaluate(id=>window.aux.invoke('tasks.get',{taskId:id}),task.taskId);
 assert.equal(final.task.objective,'My unfinished local revision');
 assert.equal(final.revisions.length,3);
 console.log('Task drafts survive workspace switches and reload; stale drafts require explicit revision review before saving.');
} finally {await app?.close();rmSync(dir,{recursive:true,force:true});}
