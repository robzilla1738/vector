import {closeAux} from "./launch.mjs";
import {launchAux,root} from './launch.mjs';
import {mkdtempSync} from 'node:fs';
import assert from 'node:assert/strict';
const dir=mkdtempSync('/tmp/aux-motion-');
const {app,page}=await launchAux({args:['--use-mock-keychain'],env:{...process.env,AUX_PROFILE_DIR:dir+'/profile',AUX_DATA_DIR:dir+'/data',AUX_LOAD_DOTENV:'0'}});
page.setDefaultTimeout(10000);
try {
 await page.locator('.aux-home').waitFor();
 await page.evaluate(()=>window.aux.invoke('settings.set',{tabLayout:'horizontal'}));
 if(await page.getByRole('button',{name:'Show sidebar',exact:true}).isVisible())await page.getByRole('button',{name:'Show sidebar',exact:true}).click();
 await page.locator('.chat-sessions[aria-busy=false]').waitFor();
 await page.getByText('Your sessions will appear here.',{exact:true}).waitFor();
 const add=page.getByRole('button',{name:'Chat options',exact:true});
 await page.locator(".chat-sidebar").evaluate(el=>Promise.all(el.getAnimations().map(animation=>animation.finished)));
 const geometry=await add.boundingBox();
 await add.hover();
 assert.deepEqual(await add.boundingBox(),geometry);
 assert.equal(await add.evaluate(el=>getComputedStyle(el).transitionDuration),'0.1s');
 assert.deepEqual(await add.locator('.ci').evaluate(el=>[el.getBoundingClientRect().width,el.getBoundingClientRect().height]),[14,14]);
 await add.focus();
 await page.keyboard.press("Tab"); await page.keyboard.press("Shift+Tab");
 assert.equal(await add.evaluate(el=>getComputedStyle(el).outlineStyle),'solid');
 await add.click();
 await page.getByRole('menuitem',{name:'New chat project',exact:true}).waitFor();
 await page.keyboard.press('Escape');
 await page.mouse.move(1000,600);
 await add.evaluate(el=>el.blur());
 assert.ok((await add.evaluate(el=>getComputedStyle(el).transitionDuration)).split(',').every(value=>parseFloat(value)===0.3));
 const back=page.getByRole('button',{name:'Back',exact:true});
 assert.equal(await back.isEnabled(),false);
 assert.equal(await back.evaluate(el=>getComputedStyle(el).opacity),'0.4');
 await page.evaluate(()=>window.aux.invoke('pages.open',{url:'about:blank',activate:true}));
 await page.locator('.horizontal-tab-select').last().click({button:'right'});
 await page.getByRole('menu').last().waitFor();
 await page.screenshot({path:root+'/release/test-artifacts/tabs/motion-menu.png'});
 await page.keyboard.press('Escape');
 await page.emulateMedia({reducedMotion:'reduce'});
 await add.hover();
 assert.ok((await add.evaluate(el=>getComputedStyle(el).transitionDuration)).split(',').every(value=>parseFloat(value)===0));
 await page.locator('.horizontal-tab-select').last().click({button:'right'});
 await page.waitForFunction(()=>{const menu=document.querySelector('.ctx-menu');return menu?.isConnected&&getComputedStyle(menu).animationName==='none';});
 await page.keyboard.press('Escape');
 await page.evaluate(()=>window.aux.invoke('settings.set',{tabLayout:'vertical'}));
 if(await page.getByRole('button',{name:'Show sidebar',exact:true}).isVisible())await page.getByRole('button',{name:'Show sidebar',exact:true}).click();
 const tab=page.locator('.sidebar .tab-row.active');
 await tab.focus();
 assert.ok((await tab.evaluate(el=>getComputedStyle(el).transitionDuration)).split(',').every(value=>parseFloat(value)===0));
 await page.screenshot({path:root+'/release/test-artifacts/tabs/motion-vertical.png'});
 await page.emulateMedia({reducedMotion:'no-preference'});
 console.log('PASS hover timing, stable targets, compact icon geometry, keyboard focus, disabled states, empty chats, menus and reduced motion in both layouts.');
} finally {await closeAux(app);}
